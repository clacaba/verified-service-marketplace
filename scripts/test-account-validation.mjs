import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(resolve(root,'package.json'));const ts=require('typescript');
const source=readFileSync(resolve(root,'apps/web/lib/account-validation.ts'),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2020}}).outputText;
const {passwordFeedback,validateAccount}=await import('data:text/javascript;base64,'+Buffer.from(compiled).toString('base64'));
const base={name:'Demo User',email:'demo@example.test',password:'ValidPassword!123',confirmPassword:'ValidPassword!123',accountType:'Customer'};
assert.equal(passwordFeedback('').level,'empty');
assert.equal(passwordFeedback('abc').level,'weak');
assert.equal(passwordFeedback('LongPassword123').level,'medium');
assert.equal(passwordFeedback(base.password).level,'strong');
assert.equal(passwordFeedback(base.password).valid,true);
for(const password of ['Short!1Aa','longpassword!123','LONGPASSWORD!123','LongPasswordOnly!','LongPassword123','A1!'+'a'.repeat(126)])assert.equal(passwordFeedback(password).valid,false);
assert.equal(passwordFeedback('A1!'+'a'.repeat(125)).valid,true);
assert.deepEqual(validateAccount(base,true),{});
assert.equal(Object.keys(validateAccount({...base,name:'   ',email:'not-an-email',password:'a',confirmPassword:'b',accountType:'Reviewer'},true)).length,5);
assert.ok(validateAccount({...base,confirmPassword:''},true).confirmPassword);
assert.ok(validateAccount({...base,name:'a'.repeat(151)},true).name);
assert.ok(validateAccount({...base,email:'x'.repeat(250)+'@test'},true).email);
assert.deepEqual(validateAccount({...base,password:'legacy',confirmPassword:''},false),{});
assert.ok(validateAccount({...base,password:''},false).password);
assert.ok(validateAccount({...base,password:'a'.repeat(129)},false).password);
assert.deepEqual(validateAccount({...base,email:' demo@example.test '},true),{});
// Server rendering checks prove semantic controls/labels are present without
// claiming real browser interaction or color/layout acceptance testing.
const vm=require('node:vm');const React=require('react');const {renderToStaticMarkup}=require('react-dom/server');
const component=ts.transpileModule(readFileSync(resolve(root,'apps/web/app/account-form.tsx'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2020}}).outputText;
const module={exports:{}};
vm.runInNewContext(component,{exports:module.exports,require:(name)=>name==='next/navigation'?{useRouter:()=>({push(){},refresh(){}})}:name==='next/link'?{default:({children,...props})=>React.createElement('a',props,children)}:name==='../lib/auth-client'?{authRequest(){throw new Error('Rendering must not submit')}}:name==='../lib/account-validation'?{passwordFeedback,validateAccount}:require(name)});
const registration=renderToStaticMarkup(React.createElement(module.exports.default,{mode:'register'}));
const login=renderToStaticMarkup(React.createElement(module.exports.default,{mode:'login'}));
assert.match(registration,/aria-label="Show password"/);assert.match(registration,/aria-label="Show confirm password"/);
assert.match(registration,/name="confirmPassword"/);assert.match(registration,/password-checklist/);
assert.equal((registration.match(/class="required-marker" aria-hidden="true"/g)||[]).length,5);
assert.match(login,/aria-label="Show password"/);assert.doesNotMatch(login,/name="confirmPassword"/);assert.doesNotMatch(login,/password-checklist/);
assert.match(registration,/type="button"/);assert.match(registration,/aria-pressed="false"/);
console.log('PASS: password feedback, registration/login validation, boundary cases, and server-rendered form controls.');
