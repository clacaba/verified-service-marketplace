using Marketplace.Api.Bookings;
using Marketplace.Api.CustomerReviews;
using Marketplace.Api.Properties;
using Marketplace.Api.Catalog;
using Marketplace.Api.Review;
using Marketplace.Api.Verification;
using Marketplace.Api.Providers;
using Marketplace.Api.Identity;
using Marketplace.Api.Organizations;
using Microsoft.AspNetCore.Identity.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore;
namespace Marketplace.Api.Data;

public sealed class MarketplaceDbContext(DbContextOptions<MarketplaceDbContext> options) : IdentityDbContext<Account>(options)
{
    public DbSet<BookingReview> BookingReviews => Set<BookingReview>();
    public DbSet<ProviderReviewReply> ProviderReviewReplies => Set<ProviderReviewReply>();
    public DbSet<ProviderSchedule> ProviderSchedules => Set<ProviderSchedule>();
    public DbSet<Booking> Bookings => Set<Booking>();
    public DbSet<BookingEvent> BookingEvents => Set<BookingEvent>();
    public DbSet<BookingNotice> BookingNotices => Set<BookingNotice>();
    public DbSet<CustomerProperty> CustomerProperties => Set<CustomerProperty>();
    public DbSet<ServiceImage> ServiceImages => Set<ServiceImage>();
    public DbSet<ServiceImageDeletion> ServiceImageDeletions => Set<ServiceImageDeletion>();
    public DbSet<ServiceListing> ServiceListings => Set<ServiceListing>();
    public DbSet<AccountSession> AccountSessions => Set<AccountSession>();
    public DbSet<VerificationEmail> VerificationEmails => Set<VerificationEmail>();
    public DbSet<Organization> Organizations => Set<Organization>();
    public DbSet<OrganizationMembership> OrganizationMemberships => Set<OrganizationMembership>();
    public DbSet<OrganizationInvitation> OrganizationInvitations => Set<OrganizationInvitation>();
    public DbSet<OrganizationAuditEvent> OrganizationAuditEvents => Set<OrganizationAuditEvent>();
    public DbSet<ProviderProfile> ProviderProfiles => Set<ProviderProfile>();
    public DbSet<ServiceCategory> ServiceCategories => Set<ServiceCategory>();
    public DbSet<ProviderCategory> ProviderCategories => Set<ProviderCategory>();
    public DbSet<VerificationApplication> VerificationApplications => Set<VerificationApplication>();
    public DbSet<VerificationDocument> VerificationDocuments => Set<VerificationDocument>();
    public DbSet<EvidenceDeletion> EvidenceDeletions => Set<EvidenceDeletion>();
    public DbSet<VerificationDecision> VerificationDecisions => Set<VerificationDecision>();
    public DbSet<VerificationCheck> VerificationChecks => Set<VerificationCheck>();
    public DbSet<Notification> Notifications => Set<Notification>();
    public DbSet<PlatformAccessAudit> PlatformAccessAudits => Set<PlatformAccessAudit>();
    protected override void OnModelCreating(ModelBuilder builder)
    {
        base.OnModelCreating(builder);
        builder.Entity<ProviderReviewReply>().HasKey(r => r.BookingId);
        builder.Entity<BookingReview>().HasOne(r => r.Reply).WithOne().HasForeignKey<ProviderReviewReply>(r => r.BookingId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<ProviderReviewReply>().HasOne<Account>().WithMany().HasForeignKey(r => r.ActorId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<ProviderReviewReply>().Property(r => r.Comment).HasMaxLength(2000);
        builder.Entity<ProviderReviewReply>().ToTable(t => t.HasCheckConstraint("CK_ProviderReviewReply_Comment", "length(trim(\"Comment\")) >= 1 AND length(\"Comment\") <= 2000"));
        builder.Entity<BookingReview>().HasKey(r => r.BookingId);
        builder.Entity<BookingReview>().HasOne(r => r.Booking).WithMany().HasForeignKey(r => r.BookingId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<BookingReview>().Property(r => r.Comment).HasMaxLength(2000);
        builder.Entity<BookingReview>().Property(r => r.Status).HasMaxLength(20);
        builder.Entity<BookingReview>().HasIndex(r => new { r.Status, r.CreatedAt });
        builder.Entity<BookingReview>().ToTable(t =>
        {
            t.HasCheckConstraint("CK_BookingReview_Rating", "\"Rating\" >= 1 AND \"Rating\" <= 5");
            // Minimum feedback length is validated in UTF-16 by the API/browser. SQL counts Unicode code points.
            t.HasCheckConstraint("CK_BookingReview_Comment", "length(trim(\"Comment\")) >= 1 AND length(\"Comment\") <= 2000");
            t.HasCheckConstraint("CK_BookingReview_Status", "\"Status\" IN ('Published','Hidden')");
        });
        builder.Entity<ProviderSchedule>().HasOne<Organization>().WithMany().HasForeignKey(s => s.Id).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<ProviderSchedule>().Property(s => s.Version).IsConcurrencyToken();
        builder.Entity<Booking>().Property(b => b.Version).IsConcurrencyToken();
        builder.Entity<Booking>().Property(b => b.Status).HasMaxLength(40);
        builder.Entity<Booking>().ToTable(t =>
        {
            t.HasCheckConstraint("CK_Booking_Interval", "\"StartsAt\" < \"EndsAt\" AND \"ReservedFrom\" <= \"StartsAt\" AND \"ReservedUntil\" >= \"EndsAt\"");
            t.HasCheckConstraint("CK_Booking_Status", "\"Status\" IN ('PendingProviderConfirmation','Confirmed','InProgress','Completed','Declined','Expired','CancelledByCustomer','CancelledByProvider')");
        });
        builder.Entity<Booking>().HasOne<Organization>().WithMany().HasForeignKey(b => b.OrganizationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Booking>().HasOne<ServiceListing>().WithMany().HasForeignKey(b => b.ServiceId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Booking>().HasOne<CustomerProperty>().WithMany().HasForeignKey(b => b.PropertyId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Booking>().HasOne<Account>().WithMany().HasForeignKey(b => b.CustomerId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Booking>().HasIndex(b => new { b.OrganizationId, b.Status, b.ReservedFrom, b.ReservedUntil });
        builder.Entity<Booking>().HasIndex(b => new { b.CustomerId, b.StartsAt });
        builder.Entity<Booking>().HasIndex(b => new { b.Status, b.ExpiresAt });
        builder.Entity<BookingEvent>().HasOne<Booking>().WithMany().HasForeignKey(e => e.BookingId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<BookingEvent>().Property(e => e.Reason).HasMaxLength(500);
        builder.Entity<BookingEvent>().Property(e => e.Status).HasMaxLength(40);
        builder.Entity<BookingNotice>().HasOne<Booking>().WithMany().HasForeignKey(n => n.BookingId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<BookingNotice>().HasOne<Account>().WithMany().HasForeignKey(n => n.UserId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<BookingNotice>().Property(n => n.Message).HasMaxLength(200);
        builder.Entity<BookingNotice>().HasIndex(n => new { n.UserId, n.CreatedAt });
        builder.Entity<CustomerProperty>().HasOne<Account>().WithMany().HasForeignKey(p => p.CustomerId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<CustomerProperty>().Property(p => p.Version).IsConcurrencyToken();
        builder.Entity<CustomerProperty>().Property(p => p.Label).HasMaxLength(80);
        builder.Entity<CustomerProperty>().Property(p => p.AddressLine1).HasMaxLength(200);
        builder.Entity<CustomerProperty>().Property(p => p.AddressLine2).HasMaxLength(200);
        builder.Entity<CustomerProperty>().Property(p => p.City).HasMaxLength(100);
        builder.Entity<CustomerProperty>().Property(p => p.Region).HasMaxLength(100);
        builder.Entity<CustomerProperty>().Property(p => p.PostalCode).HasMaxLength(20);
        builder.Entity<CustomerProperty>().Property(p => p.CountryCode).HasMaxLength(2);
        builder.Entity<CustomerProperty>().HasIndex(p => new { p.CustomerId, p.ArchivedAt });
        builder.Entity<ServiceListing>().HasMany(x => x.Images).WithOne().HasForeignKey(x => x.ServiceId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<ServiceImage>().Property(x => x.AltText).HasMaxLength(150);
        builder.Entity<ServiceImage>().Property(x => x.ObjectKey).HasMaxLength(200);
        builder.Entity<ServiceImage>().HasIndex(x => x.ObjectKey).IsUnique();
        builder.Entity<ServiceImage>().Property(x => x.Sha256).HasMaxLength(64);
        builder.Entity<ServiceImageDeletion>().Property(x => x.ObjectKey).HasMaxLength(200);
        builder.Entity<ServiceImageDeletion>().HasIndex(x => x.DueAt);
        builder.Entity<ServiceListing>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<ServiceListing>().HasOne<ServiceCategory>().WithMany().HasForeignKey(x => x.CategoryId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<ServiceListing>().Property(x => x.Title).HasMaxLength(150);
        builder.Entity<ServiceListing>().Property(x => x.Description).HasMaxLength(4000);
        builder.Entity<ServiceListing>().Property(x => x.ServiceArea).HasMaxLength(250);
        builder.Entity<ServiceListing>().Property(x => x.Currency).HasMaxLength(3);
        builder.Entity<ServiceListing>().Property(x => x.Status).HasMaxLength(20);
        builder.Entity<ServiceListing>().Property(x => x.Version).IsConcurrencyToken();
        builder.Entity<ServiceListing>().HasIndex(x => new { x.OrganizationId, x.Status });
        builder.Entity<ServiceListing>().HasIndex(x => new { x.Status, x.CategoryId, x.PriceMinor });
        builder.Entity<ServiceListing>().ToTable(t =>
        {
            t.HasCheckConstraint("CK_ServiceListing_Price", "\"PriceMinor\" >= 1 AND \"PriceMinor\" <= 100000000");
            t.HasCheckConstraint("CK_ServiceListing_Duration", "\"DurationMinutes\" >= 15 AND \"DurationMinutes\" <= 1440 AND \"DurationMinutes\" % 15 = 0");
            t.HasCheckConstraint("CK_ServiceListing_Currency", "\"Currency\" = 'PHP'");
            t.HasCheckConstraint("CK_ServiceListing_Status", "\"Status\" IN ('Draft', 'Published', 'Archived')");
        });
        builder.Entity<VerificationApplication>().HasOne<VerificationApplication>().WithMany().HasForeignKey(x => x.ParentApplicationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationApplication>().HasIndex(x => x.ParentApplicationId).IsUnique().HasFilter("\"ParentApplicationId\" IS NOT NULL");
        builder.Entity<VerificationApplication>().HasOne<Account>().WithMany().HasForeignKey(x => x.ReviewStartedBy).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationApplication>().HasMany(x => x.Decisions).WithOne().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationDecision>().HasOne<Account>().WithMany().HasForeignKey(x => x.ReviewerId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationDecision>().Property(x => x.Decision).HasMaxLength(40);
        builder.Entity<VerificationDecision>().Property(x => x.Reason).HasMaxLength(2000);
        builder.Entity<VerificationDecision>().HasMany(x => x.Checks).WithOne().HasForeignKey(x => x.DecisionId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationCheck>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationCheck>().Property(x => x.Type).HasMaxLength(40);
        builder.Entity<VerificationCheck>().HasIndex(x => new { x.OrganizationId, x.ExpiresAt });
        builder.Entity<Notification>().HasOne<Account>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Notification>().HasOne<VerificationApplication>().WithMany().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Notification>().Property(x => x.Message).HasMaxLength(2200);
        builder.Entity<Notification>().HasIndex(x => new { x.UserId, x.CreatedAt });
        builder.Entity<PlatformAccessAudit>().HasOne<Account>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationApplication>().Property(x => x.Version).IsConcurrencyToken();
        builder.Entity<VerificationApplication>().Property(x => x.Status).HasMaxLength(40);
        builder.Entity<VerificationApplication>().HasIndex(x => x.OrganizationId).IsUnique().HasFilter("\"IsActive\" = TRUE");
        builder.Entity<VerificationApplication>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationApplication>().HasOne<ProviderProfile>().WithMany().HasForeignKey(x => x.ProviderId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<VerificationApplication>().HasMany(x => x.Documents).WithOne().HasForeignKey(x => x.ApplicationId);
        builder.Entity<VerificationDocument>().Property(x => x.Version).IsConcurrencyToken();
        builder.Entity<VerificationDocument>().Property(x => x.ObjectKey).HasMaxLength(200);
        builder.Entity<VerificationDocument>().HasIndex(x => x.ObjectKey).IsUnique();
        builder.Entity<VerificationDocument>().HasIndex(x => x.ExpiresAt);
        builder.Entity<VerificationDocument>().Property(x => x.FileName).HasMaxLength(120);
        builder.Entity<VerificationDocument>().Property(x => x.ContentType).HasMaxLength(50);
        builder.Entity<VerificationDocument>().Property(x => x.EvidenceType).HasMaxLength(40);
        builder.Entity<VerificationDocument>().Property(x => x.Sha256).HasMaxLength(64);
        builder.Entity<EvidenceDeletion>().Property(x => x.ObjectKey).HasMaxLength(200);
        builder.Entity<EvidenceDeletion>().HasIndex(x => x.DueAt);
        builder.Entity<ProviderProfile>().HasIndex(x => x.OrganizationId).IsUnique();
        builder.Entity<ProviderProfile>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId);
        builder.Entity<ProviderProfile>().Property(x => x.DisplayName).HasMaxLength(150);
        builder.Entity<ProviderProfile>().Property(x => x.ProviderType).HasMaxLength(20);
        builder.Entity<ProviderProfile>().Property(x => x.Biography).HasMaxLength(4000);
        builder.Entity<ProviderProfile>().Property(x => x.ServiceArea).HasMaxLength(250);
        builder.Entity<ProviderProfile>().Property(x => x.Version).IsConcurrencyToken();
        builder.Entity<ServiceCategory>().Property(x => x.Name).HasMaxLength(100);
        builder.Entity<ServiceCategory>().HasData(
            new ServiceCategory { Id = Guid.Parse("10000000-0000-0000-0000-000000000001"), Name = "Cleaning" },
            new ServiceCategory { Id = Guid.Parse("10000000-0000-0000-0000-000000000002"), Name = "Plumbing" },
            new ServiceCategory { Id = Guid.Parse("10000000-0000-0000-0000-000000000003"), Name = "Electrical" },
            new ServiceCategory { Id = Guid.Parse("10000000-0000-0000-0000-000000000004"), Name = "Appliance repair" });
        builder.Entity<ProviderCategory>().HasKey(x => new { x.ProfileId, x.CategoryId });
        builder.Entity<ProviderProfile>().HasMany(x => x.Categories).WithOne().HasForeignKey(x => x.ProfileId);
        builder.Entity<ProviderCategory>().HasOne<ServiceCategory>().WithMany().HasForeignKey(x => x.CategoryId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<Account>().Property(x => x.DisplayName).HasMaxLength(150);
        builder.Entity<Account>().Property(x => x.AccountType).HasMaxLength(20);
        builder.Entity<Account>().HasIndex(x => x.NormalizedEmail).IsUnique();
        builder.Entity<AccountSession>().HasOne<Account>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
        builder.Entity<AccountSession>().HasIndex(x => x.UserId);
        builder.Entity<VerificationEmail>().HasIndex(x => x.NextAttemptAt);
        builder.Entity<VerificationEmail>().Property(x => x.Subject).HasMaxLength(200);
        builder.Entity<Organization>().Property(x => x.Name).HasMaxLength(150);
        builder.Entity<Organization>().Property(x => x.ProviderType).HasMaxLength(20);
        builder.Entity<OrganizationMembership>().HasKey(x => new { x.OrganizationId, x.UserId });
        builder.Entity<OrganizationMembership>().Property(x => x.Role).HasMaxLength(20);
        builder.Entity<OrganizationMembership>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId);
        builder.Entity<OrganizationMembership>().HasOne<Account>().WithMany().HasForeignKey(x => x.UserId);
        builder.Entity<OrganizationInvitation>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId);
        builder.Entity<OrganizationInvitation>().HasIndex(x => x.TokenHash).IsUnique();
        builder.Entity<OrganizationInvitation>().Property(x => x.TokenHash).HasMaxLength(64);
        builder.Entity<OrganizationInvitation>().Property(x => x.Email).HasMaxLength(254);
        builder.Entity<OrganizationInvitation>().Property(x => x.NormalizedEmail).HasMaxLength(254);
        builder.Entity<OrganizationInvitation>().Property(x => x.Role).HasMaxLength(20);
        builder.Entity<OrganizationInvitation>().Property(x => x.Version).IsConcurrencyToken();
        builder.Entity<OrganizationAuditEvent>().HasOne<Organization>().WithMany().HasForeignKey(x => x.OrganizationId);
        builder.Entity<OrganizationAuditEvent>().HasOne<Account>().WithMany().HasForeignKey(x => x.ActorId).OnDelete(DeleteBehavior.Restrict);
        builder.Entity<OrganizationAuditEvent>().HasIndex(x => new { x.OrganizationId, x.OccurredAt });
    }
}
